const showcase = (
  input: Omit<
    PresetInput,
    | 'family'
    | 'sourceRepository'
    | 'sourceUrl'
    | 'renderer'
    | 'nativeWidth'
    | 'nativeHeight'
    | 'nativeRadius'
  >,
): ReferenceButtonPreset => {
  const exactConfig =
    LIQUID_DOM_SHOWCASE_BUTTON_CONFIG_BY_ID[input.id];
  if (!exactConfig) {
    throw new Error(
      `Missing exact Liquid DOM showcase config for ${input.id}`,
    );
  }
  const requiredAssets = [
    ...(input.requiredAssets ?? []),
    ...(exactConfig.sourceMode === 'liquid-dom-webgpu'
      ? [
          '@liquid-dom/react authoritative local build',
          'live button placement stage capture',
        ]
      : []),
  ];

  return preset({
    family: 'liquid-dom-showcase',
    sourceRepository: GLASS_REPO,
    sourceUrl: 'https://glass-projects-lab-showcase.vercel.app/',
    renderer: 'liquid-dom-showcase',
    ...input,
    nativeWidth: exactConfig.geometry.width,
    nativeHeight: exactConfig.geometry.height,
    nativeRadius: exactConfig.geometry.radius,
    requiredAssets: [...new Set(requiredAssets)],
    options: {
      ...input.options,
      exactConfigId: exactConfig.id,
      sourceMode: exactConfig.sourceMode,
      sourceKind: exactConfig.kind,
    },
  });
};

